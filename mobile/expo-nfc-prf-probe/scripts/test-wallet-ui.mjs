import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';

const source = readFileSync('src/cardIdentity.ts', 'utf8');
const compiled = ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.ES2022,target:ts.ScriptTarget.ES2022}}).outputText;
const {cardInfoUrl, displayUsername, displayBalance, knownCards} = await import('data:text/javascript;base64,'+Buffer.from(compiled).toString('base64'));
const key = Object.keys(knownCards)[0];
const query = new URL(cardInfoUrl(key));
assert.equal(query.searchParams.get('client_pk33'), key);
assert.equal(query.searchParams.get('cred_id_b64u'), knownCards[key]);
assert.equal(new URL(cardInfoUrl('unknown')).searchParams.has('cred_id_b64u'), false);
assert.equal(displayUsername('arkade'), '@arkade');
assert.equal(displayUsername('@arkade'), '@arkade');
assert.equal(displayUsername('arkade@nuri.com'), '@arkade');
assert.equal(displayUsername(null), '');
assert.equal(displayBalance(1337), '1,337 sats');
assert.equal(displayBalance(0), '0 sats');
const screen = readFileSync('WalletScreen.tsx', 'utf8');
const fontSizes = [...new Set([...screen.matchAll(/fontSize:\s*(\d+)/g)].map(m=>Number(m[1])))].sort((a,b)=>a-b);
assert.deepEqual(fontSizes,[17,28]);
assert.ok(!screen.includes('useEffect'), 'no automatic scan before tap');
assert.ok(screen.includes("button('Scan card',()=>void run(load))"));
assert.ok(screen.includes('Hold your Nuri card to the phone'));
assert.ok(!screen.includes("button('Name'"));
assert.ok(screen.includes('onLongPress'));
assert.ok(screen.includes("software?'Use real card':'Use software card'"));
assert.ok(screen.includes('await withPinCard(signing?p:\'\',()=>{},fn)'));
assert.ok(screen.includes('await receiveWallet(key)'));
assert.ok(screen.includes('await openWallet(key)'));
assert.ok(screen.includes("minHeight:56,borderRadius:14,padding:18"));
console.log('PASS credential-bound username query, @arkade formatting, 1,337 sats formatting');
console.log('PASS Solarized wallet UI guard: 17/28px only, explicit Scan card, card prompt, buttons, preserved NFC/wallet/demo wiring');
