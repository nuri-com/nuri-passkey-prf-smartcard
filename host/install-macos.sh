#!/usr/bin/env bash
# Install the Nuri Card native messaging host for Google Chrome on macOS.
#
#   host/install-macos.sh [--sim] [--python /path/to/python3.13] [--extension-id <id>]
#
# - Creates a venv at ~/.nuri-card-host-venv (python-ecdsa + pycryptodome; pyscard is
#   taken from the repo's card venv if present, otherwise installed here too).
# - Writes a launcher at ~/.nuri-card-host/run.sh that execs host/nuri_card_host.py.
# - Writes ~/Library/Application Support/Google/Chrome/NativeMessagingHosts/com.nuri.card.json.
# Uninstall: host/install-macos.sh --uninstall
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/.." && pwd)"
HOST_PY="$HERE/nuri_card_host.py"
MANIFEST_DIR="$HOME/Library/Application Support/Google/Chrome/NativeMessagingHosts"
MANIFEST="$MANIFEST_DIR/com.nuri.card.json"
VENV="$HOME/.nuri-card-host-venv"
LAUNCH_DIR="$HOME/.nuri-card-host"
LAUNCHER="$LAUNCH_DIR/run.sh"
PYTHON="${PYTHON:-/opt/homebrew/bin/python3.13}"
# Fixed ID derived from the "key" field in extension/manifest.json.
EXT_ID="hlljlndpkgephgelnfgcpnneecmklnmf"
SIM=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --sim) SIM=1 ;;
    --python) PYTHON="$2"; shift ;;
    --extension-id) EXT_ID="$2"; shift ;;
    --uninstall) rm -f "$MANIFEST" "$LAUNCHER"; echo "removed $MANIFEST"; exit 0 ;;
    -h|--help) sed -n 2,12p "$0"; exit 0 ;;
    *) echo "unknown arg $1" >&2; exit 2 ;;
  esac
  shift
done

[[ -x "$PYTHON" ]] || { echo "python not found at $PYTHON (brew install python@3.13 or pass --python)" >&2; exit 1; }

if [[ ! -x "$VENV/bin/python" ]]; then
  "$PYTHON" -m venv "$VENV"
fi
"$VENV/bin/pip" install -q --upgrade "ecdsa>=0.19" "pycryptodome>=3.20" pyscard >/dev/null

mkdir -p "$LAUNCH_DIR" "$MANIFEST_DIR"
cat > "$LAUNCHER" <<EOF
#!/usr/bin/env bash
# Generated by host/install-macos.sh. Chrome runs this with the extension origin as \$1.
export NURI_CARD_SIM="${SIM}"
export NURI_CARD_HOST_LOG="\${NURI_CARD_HOST_LOG:-$LAUNCH_DIR/host.log}"
exec "$VENV/bin/python" "$HOST_PY" "\$@"
EOF
chmod +x "$LAUNCHER"

cat > "$MANIFEST" <<EOF
{
  "name": "com.nuri.card",
  "description": "Nuri Card Ethereum signer (native messaging host)",
  "path": "$LAUNCHER",
  "type": "stdio",
  "allowed_origins": ["chrome-extension://$EXT_ID/"]
}
EOF

echo "installed: $MANIFEST"
echo "launcher:  $LAUNCHER (NURI_CARD_SIM=$SIM)"
echo "extension: chrome://extensions -> Load unpacked -> $REPO/extension (expected ID $EXT_ID)"

# Smoke test the host through the launcher with the same framing Chrome uses.
"$VENV/bin/python" - "$LAUNCHER" "$EXT_ID" <<'PY'
import json, struct, subprocess, sys
launcher, ext_id = sys.argv[1:3]
body = json.dumps({"id": 1, "method": "info"}).encode()
out = subprocess.run([launcher, f"chrome-extension://{ext_id}/"], input=struct.pack("<I", len(body)) + body, capture_output=True, check=True).stdout
(n,) = struct.unpack("<I", out[:4])
print("host smoke test:", out[4:4 + n].decode())
PY
