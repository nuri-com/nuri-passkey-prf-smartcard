#!/usr/bin/env bash
# Install the Nuri Card native messaging host for Google Chrome on macOS.
#
#   host/install-macos.sh [--sim] [--eth1-demo] [--python /path/to/python3.13] [--extension-id <id>]
#
# --eth1-demo: the launcher exports NURI_ALLOW_ETH1_DEMO=1 so Chrome can use a card that
#   only has the legacy PIN-less ETH1 applet (public demo card). Without it the launcher
#   unsets the variable and such a card is refused (ETH1_DEMO_DISABLED).
#
# - Creates a venv at ~/.nuri-card-host-venv (python-ecdsa + pycryptodome; pyscard is
#   taken from the repo's card venv if present, otherwise installed here too).
# - Copies host + PCSC/attestation helpers and SHA256SUMS into ~/.nuri-card-host.
# - Writes ~/.nuri-card-host/run.sh to exec that self-contained host snapshot.
# - Writes ~/Library/Application Support/Google/Chrome/NativeMessagingHosts/com.nuri.card.json.
# Uninstall: host/install-macos.sh --uninstall
# Test hook: NURI_HOST_INSTALL_LAUNCHER_ONLY=1 writes only the launcher (no venv,
# no pip, no manifest, no smoke test) so host/test_host.py can check it offline.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/.." && pwd)"
HOST_PY="$HERE/nuri_card_host.py"
MANIFEST_DIR="$HOME/Library/Application Support/Google/Chrome/NativeMessagingHosts"
MANIFEST="$MANIFEST_DIR/com.nuri.card.json"
VENV="$HOME/.nuri-card-host-venv"
LAUNCH_DIR="$HOME/.nuri-card-host"
LAUNCHER="$LAUNCH_DIR/run.sh"
PYTHON="${PYTHON:-/opt/homebrew/bin/python3.13}"
# Fixed ID derived from the "key" field in extension/manifest.json.
EXT_ID="hlljlndpkgephgelnfgcpnneecmklnmf"
SIM=0
ETH1_DEMO=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --sim) SIM=1 ;;
    --eth1-demo) ETH1_DEMO=1 ;;
    --python) PYTHON="$2"; shift ;;
    --extension-id) EXT_ID="$2"; shift ;;
    --uninstall) rm -f "$MANIFEST" "$LAUNCHER"; echo "removed $MANIFEST"; exit 0 ;;
    -h|--help) sed -n 2,16p "$0"; exit 0 ;;
    *) echo "unknown arg $1" >&2; exit 2 ;;
  esac
  shift
done

if [[ "${NURI_HOST_INSTALL_LAUNCHER_ONLY:-}" != 1 ]]; then
[[ -x "$PYTHON" ]] || { echo "python not found at $PYTHON (brew install python@3.13 or pass --python)" >&2; exit 1; }

if [[ ! -x "$VENV/bin/python" ]]; then
  "$PYTHON" -m venv "$VENV"
fi
"$VENV/bin/pip" install -q --upgrade "ecdsa>=0.19" "pycryptodome>=3.20" pyscard "fido2[pcsc]>=2.2,<3" >/dev/null
fi

mkdir -p "$LAUNCH_DIR"
if [[ "${NURI_HOST_INSTALL_LAUNCHER_ONLY:-}" != 1 ]]; then
  # Keep a self-contained installed snapshot, including both public verifiers.
  # Preserve the repo layout used by the host to locate its scripts directory.
  mkdir -p "$LAUNCH_DIR/host" "$LAUNCH_DIR/scripts"
  cp "$HERE/nuri_card_host.py" "$LAUNCH_DIR/host/nuri_card_host.py"
  cp "$HERE/webauthn_bridge.py" "$LAUNCH_DIR/host/webauthn_bridge.py"
  cp "$REPO/scripts/nuri_pcsc.py" "$REPO/scripts/nuri_attest.py" "$LAUNCH_DIR/scripts/"
  (cd "$LAUNCH_DIR" && shasum -a 256 host/nuri_card_host.py host/webauthn_bridge.py scripts/nuri_pcsc.py scripts/nuri_attest.py > SHA256SUMS
    shasum -a 256 -c SHA256SUMS)
  HOST_PY="$LAUNCH_DIR/host/nuri_card_host.py"
fi
# Sim is a PUBLIC known key (R8). Only an explicit --sim install exports
# NURI_CARD_SIM=1 and passes --sim; a normal launcher unsets any inherited value
# so a stray environment variable can never turn a card wallet into the sim.
if [[ "$SIM" == 1 ]]; then
  SIM_ENV='export NURI_CARD_SIM=1'
  SIM_ARG=' --sim'
else
  SIM_ENV='unset NURI_CARD_SIM'
  SIM_ARG=''
fi
if [[ "$ETH1_DEMO" == 1 ]]; then
  DEMO_ENV='export NURI_ALLOW_ETH1_DEMO=1  # PIN-less legacy ETH1 demo card allowed (--eth1-demo)'
else
  DEMO_ENV='unset NURI_ALLOW_ETH1_DEMO'
fi
cat > "$LAUNCHER" <<EOF
#!/usr/bin/env bash
# Generated by host/install-macos.sh. Chrome runs this with the extension origin as \$1.
$SIM_ENV
$DEMO_ENV
export NURI_CARD_HOST_LOG="\${NURI_CARD_HOST_LOG:-$LAUNCH_DIR/host.log}"
exec "$VENV/bin/python" "$HOST_PY"$SIM_ARG "\$@"
EOF
chmod +x "$LAUNCHER"
if [[ "${NURI_HOST_INSTALL_LAUNCHER_ONLY:-}" == 1 ]]; then echo "launcher: $LAUNCHER"; exit 0; fi
mkdir -p "$MANIFEST_DIR"

cat > "$MANIFEST" <<EOF
{
  "name": "com.nuri.card",
  "description": "Nuri Card Ethereum signer (native messaging host)",
  "path": "$LAUNCHER",
  "type": "stdio",
  "allowed_origins": ["chrome-extension://$EXT_ID/"]
}
EOF

echo "installed: $MANIFEST"
if [[ "$SIM" == 1 ]]; then
  echo "launcher:  $LAUNCHER (SIMULATOR: public known key, never fund its address)"
else
  echo "launcher:  $LAUNCHER (card mode)"
fi
[[ "$ETH1_DEMO" == 1 ]] && echo "WARNING:   --eth1-demo: the PIN-less legacy ETH1 applet may sign (public demo card only)"
echo "extension: chrome://extensions -> Load unpacked -> $REPO/extension (expected ID $EXT_ID)"

# Smoke test the host through the launcher with the same framing Chrome uses.
"$VENV/bin/python" - "$LAUNCHER" "$EXT_ID" <<'PY'
import json, struct, subprocess, sys
launcher, ext_id = sys.argv[1:3]
body = json.dumps({"id": 1, "method": "info"}).encode()
out = subprocess.run([launcher, f"chrome-extension://{ext_id}/"], input=struct.pack("<I", len(body)) + body, capture_output=True, check=True).stdout
(n,) = struct.unpack("<I", out[:4])
print("host smoke test:", out[4:4 + n].decode())
PY
